// Generate SQL to rewrite stored curve_key/c4/c6 values to the exact
// global-minimal-model invariants used by the current verifier.
//
// Usage:
//   node scripts/backfill-curve-keys.mjs > /tmp/curve-key-migration.sql
//   wrangler d1 execute elliptic-rank --remote --file /tmp/curve-key-migration.sql
//
// Input defaults to SITE/database.json; override with ERANK_SITE or with a local
// ERANK_DATABASE_FILE containing the same JSON shape.

import fs from 'node:fs'
import { canonicalKey } from '../src/verify.ts'

const SITE = (process.env.ERANK_SITE ?? 'https://elliptic-rank.icarm.cloud').replace(/\/+$/, '')
const DATABASE_FILE = process.env.ERANK_DATABASE_FILE ?? null

function sqlString(s) {
  return `'${String(s).replace(/'/g, "''")}'`
}

async function loadDatabase() {
  if (DATABASE_FILE) {
    return JSON.parse(fs.readFileSync(DATABASE_FILE, 'utf8'))
  }
  const res = await fetch(`${SITE}/database.json`, {
    headers: { accept: 'application/json', 'cache-control': 'no-cache' },
  })
  if (!res.ok) throw new Error(`${SITE}/database.json: HTTP ${res.status}`)
  return res.json()
}

async function initGp() {
  const factory = (await import('@sagemath/pari/dist/gp-sta.js')).default
  const wasmBinary = fs.readFileSync('src/gp-sta.wasm')
  const mod = await factory({
    noInitialRun: true,
    print: () => {},
    printErr: () => {},
    instantiateWasm(imports, recv) {
      const inst = new WebAssembly.Instance(new WebAssembly.Module(wasmBinary), imports)
      recv(inst)
      return inst.exports
    },
  })
  mod.ccall('gp_embedded_init', null, ['number', 'number'], [16 << 20, 16 << 20])
  return mod.cwrap('gp_embedded', 'string', ['string'])
}

function curveAinvs(curve) {
  if (Array.isArray(curve.ainvs)) return curve.ainvs
  if (typeof curve.ainvs === 'string') return JSON.parse(curve.ainvs)
  throw new Error(`#${curve.id}: missing ainvs`)
}

const db = await loadDatabase()
if (!db || !Array.isArray(db.curves)) {
  throw new Error('database JSON did not contain a curves array')
}

const gp = await initGp()
const rows = db.curves.map((curve) => {
  if (!Number.isInteger(curve.id)) throw new Error(`bad curve id: ${curve.id}`)
  if (typeof curve.curve_key !== 'string') throw new Error(`#${curve.id}: missing curve_key`)
  const canonical = canonicalKey(gp, curveAinvs(curve))
  return {
    id: curve.id,
    oldKey: curve.curve_key,
    newKey: canonical.key,
    c4: canonical.c4,
    c6: canonical.c6,
  }
})

const byKey = new Map()
const collisions = []
for (const row of rows) {
  const prev = byKey.get(row.newKey)
  if (prev) collisions.push([prev, row])
  else byKey.set(row.newKey, row)
}

if (collisions.length > 0) {
  console.error('new curve_key collisions; merge these rows manually before applying SQL:')
  for (const [a, b] of collisions) {
    console.error(`  key ${a.newKey}: #${a.id} and #${b.id}`)
  }
  process.exit(1)
}

const changed = rows.filter((row) => row.oldKey !== row.newKey)

console.log('-- Generated by scripts/backfill-curve-keys.mjs')
console.log(`-- Rows checked: ${rows.length}; keys changed: ${changed.length}`)
console.log('-- Review before applying to D1.')
if (changed.length === 0) {
  console.log('-- No curve_key/c4/c6 updates needed.')
  process.exit(0)
}
console.log('-- Changed rows:')
for (const row of changed) {
  console.log(`--   #${row.id}: ${row.oldKey} -> ${row.newKey}`)
}
console.log('BEGIN TRANSACTION;')
for (const row of changed) {
  console.log(
    `UPDATE curves SET curve_key = ${sqlString(`__curve_key_migration_${row.id}`)} WHERE id = ${row.id};`,
  )
}
for (const row of changed) {
  console.log(
    `UPDATE curves SET curve_key = ${sqlString(row.newKey)}, c4 = ${sqlString(row.c4)}, c6 = ${sqlString(row.c6)} WHERE id = ${row.id};`,
  )
}
console.log('COMMIT;')
